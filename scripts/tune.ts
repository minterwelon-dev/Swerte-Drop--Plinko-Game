// Generates src/math/multipliers.ts. The only writer of that file.
import { writeFileSync } from 'node:fs';
import { RISKS, ROWS_OPTIONS, TUNER_SHAPE } from '../src/math/config';
import { analyticalRtp, tuneTable } from '../src/math/tuner';

const lines: string[] = [];
for (const risk of RISKS) {
  const { centre, beta, guideMax } = TUNER_SHAPE[risk];
  lines.push(`  ${risk}: {`);
  for (const rows of ROWS_OPTIONS) {
    const t = tuneTable(rows, centre, beta);
    lines.push(`    ${rows}: [${t.join(', ')}],`);
    console.log(
      `${risk.padEnd(6)} ${String(rows).padStart(2)} rows  RTP ${(analyticalRtp(t) * 100).toFixed(4)}%  ` +
        `centre ${(t[rows / 2] / 100).toFixed(2)}x  max ${(t[0] / 100).toFixed(2)}x (guide ~${guideMax[rows]}x)`,
    );
  }
  lines.push('  },');
}

const header = [
  '// GENERATED by scripts/tune.ts (npm run tune). Never hand-edit.',
  "import type { MultiplierTable, Risk, Rows } from './config';",
  '',
  'export const MULTIPLIERS: Record<Risk, Record<Rows, MultiplierTable>> = {',
];
writeFileSync(
  new URL('../src/math/multipliers.ts', import.meta.url),
  [...header, ...lines, '};', ''].join('\n'),
);
console.log('wrote src/math/multipliers.ts');
